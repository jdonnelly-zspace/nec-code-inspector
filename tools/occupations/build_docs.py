"""Build the occupation documents from the research data.

    python tools/occupations/build_docs.py

Reads docs/occupations/data/*.json and docs/occupations/proposed-skills.json and writes, in docs/occupations/:
one profile per core occupation, TRACEABILITY.md (every procedure against the app's skills and the skills still to build) and ADJACENT.md.
Edit the data files, never the generated documents.
"""
import glob
import json
import os
import re
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DOCS = os.path.join(ROOT, "docs", "occupations")
DATA = os.path.join(DOCS, "data")
CONCEPTS = os.path.join(ROOT, "Assets", "_Project", "Scripts", "Data", "ConceptIds.cs")

ATTRIBUTION = ("Occupation data comes from O*NET OnLine by the U.S. Department of Labor, Employment and Training Administration (USDOL/ETA), "
               "used under the CC BY 4.0 license, and from BLS, OSHA and trade sources listed in each section. Written in our own words.")


def skills():
    text = open(CONCEPTS, encoding="utf-8").read()
    return re.findall(r'public const string \w+ = "([a-z-]+)";', text)


def cell(text):
    return str(text).replace("|", "/").replace("\n", " ").strip()


def level(coverage):
    word = (coverage or "").strip().split(":")[0].split(" ")[0].lower().strip(" .,")
    return word if word in ("none", "partial", "good") else "none"


def write(path, lines):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines).rstrip() + "\n")


def profile(d, fname):
    L = [f"# {d['soc']} {d['title']}", "",
         "> Generated by `tools/occupations/build_docs.py` from `docs/occupations/data/" + fname + "`. Do not edit this file; edit the data.",
         "> Research summary from public sources, in our own words. **Not reviewed by an occupational expert.** " + ATTRIBUTION, "",
         "## Summary", "", d["summary"], "",
         "- O*NET: " + d["onetUrl"],
         "- BLS: " + d["bls"].get("url", ""),
         f"- Workers: {d['bls'].get('workers', '')}; growth: {d['bls'].get('growth', '')}; openings: {d['bls'].get('openings', '')}; median pay: {d['bls'].get('medianPay', '')}", "",
         "## Path into the occupation", "", d["typicalPath"], "",
         "## Tasks", "", "| Task | Importance | Electrical knowledge it needs | App skills that teach it |", "|---|---|---|---|"]
    for t in d["tasks"]:
        L.append(f"| {cell(t['task'])} | {cell(t.get('importance', ''))} | {cell(t.get('electricalKnowledge', ''))} | {cell(', '.join(t.get('appSkills', [])) or 'none')} |")
    L += ["", "## Procedures and standard operating procedures", "",
          "Each procedure is the standard, repeatable way the work is done and made safe. Steps are summaries in our own words; the standards named are the ones that govern them. "
          "Where an employer writes its own version (an SOP), these are the common elements.", ""]
    for i, p in enumerate(d["procedures"], 1):
        L += [f"### P{i}. {p['name']}", "", f"**Purpose:** {p['purpose']}", "", f"**When it is used:** {p['whenUsed']}", "", f"**Who does it:** {p['role']}", "", "**Steps**", ""]
        L += [f"{n}. {s}" for n, s in enumerate(p["steps"], 1)]
        L += ["", "**Hazards:** " + "; ".join(p["hazards"]), "", "**Controls:** " + "; ".join(p["controls"]), "", "**Standards**", ""]
        L += [f"- {s['name']}: {s['what']}" for s in p["standards"]]
        L += ["", "**Evidence**", ""] + [f"- {e['source']} ({e['says']})" for e in p["evidence"]]
        L += ["", f"**App coverage today ({level(p['appCoverage'])}):** {p['appCoverage']}", "",
              f"**Skills the app teaches that this procedure uses:** {', '.join(p['appSkills']) or 'none'}", "",
              f"**Skills still to build for it:** {', '.join(p.get('plannedSkills', [])) or 'none'}", ""]
    L += ["## Standards and codes", "", "| Standard | How this occupation uses it | NEC articles involved |", "|---|---|---|"]
    L += [f"| {cell(s['name'])} | {cell(s['role'])} | {cell(s.get('nec', ''))} |" for s in d["standardsAndCodes"]]
    L += ["", "## Work the NEC does not govern", ""] + [f"- {x}" for x in d["outsideNec"]]
    L += ["", "## Gaps for the app (from the research)", ""] + [f"- {x}" for x in d["gapsForTheApp"]]
    L += ["", "## Doubts", ""] + [f"- {x}" for x in d["doubts"]]
    return L


def traceability(occs, proposed):
    app = skills()
    P = {s["id"]: s for s in proposed["skills"]}
    L = ["# Occupation traceability", "",
         "> Generated by `tools/occupations/build_docs.py`. Do not edit; change the data in `docs/occupations/data/` or `proposed-skills.json`.", "",
         "Every procedure of the six core occupations against what the app teaches today (the code skills and the procedure skills, `ConceptIds`) and the skills still to build "
         "(`proposed-skills.json`). Coverage: **good** means the app's skills train the steps; **partial** means they train part (usually the code rules, not the method); **none** means nothing in the app teaches it.", "",
         "## Summary", "", "| Occupation | Procedures | Good | Partial | None | Share with any coverage |", "|---|---|---|---|---|---|"]
    tot = Counter()
    for fname, d in occs:
        c = Counter(level(p["appCoverage"]) for p in d["procedures"])
        n = len(d["procedures"])
        tot.update(c)
        L.append(f"| {d['soc']} {d['title'].split(' (')[0]} | {n} | {c['good']} | {c['partial']} | {c['none']} | {round(100 * (c['good'] + c['partial']) / n)}% |")
    n = sum(tot.values())
    appfile = os.path.join(ROOT, "Assets", "_Project", "StreamingAssets", "Occupations", "occupations.json")
    practice = ""
    if os.path.exists(appfile):
        procs = [p for o in json.load(open(appfile, encoding="utf-8"))["occupations"] for p in o["procedures"]]
        practice = f"{sum(1 for p in procs if p['practice'])} of {len(procs)} procedures offer step-ordering practice in the app (`StreamingAssets/Occupations/occupations.json`)."
    L += [f"| **All six** | **{n}** | **{tot['good']}** | **{tot['partial']}** | **{tot['none']}** | **{round(100 * (tot['good'] + tot['partial']) / n)}%** |", "", practice, ""]

    L += ["## Procedure by procedure", ""]
    for fname, d in occs:
        L += [f"### {d['soc']} {d['title'].split(' (')[0]}", "", "| Procedure | Coverage | App skills used | Skills still to build |", "|---|---|---|---|"]
        for p in d["procedures"]:
            L.append(f"| {cell(p['name'])} | {level(p['appCoverage'])} | {cell(', '.join(p['appSkills']) or 'none')} | {cell(', '.join(p.get('plannedSkills', [])) or 'none')} |")
        L.append("")

    use = defaultdict(list)
    for fname, d in occs:
        for p in d["procedures"]:
            for s in p["appSkills"]:
                use[s].append(d["soc"])
    L += [f"## The app's {len(app)} skills: how many procedures use each", "", "| Skill | Procedures | Occupations |", "|---|---|---|"]
    for s in sorted(app, key=lambda k: -len(use[k])):
        L.append(f"| {s} | {len(use[s])} | {', '.join(sorted(set(use[s]))) or 'none'} |")

    need = defaultdict(list)
    for fname, d in occs:
        for p in d["procedures"]:
            for s in p.get("plannedSkills", []):
                need[s].append((d["soc"], p["name"]))
    L += ["", "## Skills still to build: how many procedures need each", "", "| Skill | Wave | Status | Procedures | Occupations | Why |", "|---|---|---|---|---|---|"]
    for s in sorted(P, key=lambda k: -len(need[k])):
        socs = sorted({a for a, _ in need[s]})
        L.append(f"| {s} | {P[s].get('wave', '')} | {P[s]['status']} | {len(need[s])} | {', '.join(socs)} | {cell(P[s]['summary'])} |")
    L += ["", "The reasons, standards and first content for each are in `docs/occupations/proposed-skills.json`.", ""]
    return L


def adjacent(adj):
    L = ["# Adjacent occupations", "",
         "> Generated by `tools/occupations/build_docs.py` from `docs/occupations/data/adjacent-occupations.json`. Do not edit this file.",
         "> Research summary from public sources, in our own words, not reviewed by an occupational expert. " + ATTRIBUTION, "",
         "The market view lists 18 further occupations that need foundational electrical knowledge. Each was checked against O*NET OnLine and, where it would open, the BLS.", "",
         "## Checks on the market document's claims", "", "| Claim | Result | Note |", "|---|---|---|"]
    L += [f"| {cell(h['claim'])} | {cell(h['result'])} | {cell(h['note'])} |" for h in adj.get("headlineChecks", [])]
    L += ["", "## Occupations", "", "| SOC | Title | Cluster | Verdict | Electrical knowledge it needs | Standards | New skills needed |", "|---|---|---|---|---|---|---|"]
    for o in adj["occupations"]:
        title = o["title"] + (f" (document said: {o['docCodeCorrection']})" if o.get("docCodeCorrection") else "")
        L.append(f"| {o['soc']} | {cell(title)} | {cell(o.get('cluster', ''))} | {cell(o.get('verdict', ''))} | {cell('; '.join(o.get('electricalKnowledge', [])))} | "
                 f"{cell('; '.join(o.get('standards', [])))} | {cell('; '.join(o.get('newSkillsNeeded', [])) or 'none')} |")
    L += ["", "## Safety procedures these occupations share", ""]
    seen = Counter(x for o in adj["occupations"] for x in o.get("safetyProcedures", []))
    L += [f"- {k} ({v} occupations)" for k, v in seen.most_common(20)]
    L += ["", "## Doubts", ""] + [f"- {x}" for x in adj.get("doubts", [])]
    return L


def main():
    proposed = json.load(open(os.path.join(DOCS, "proposed-skills.json"), encoding="utf-8"))
    occs = []
    for path in sorted(glob.glob(os.path.join(DATA, "[0-9]*.json"))):
        d = json.load(open(path, encoding="utf-8"))
        occs.append((os.path.basename(path), d))
        write(os.path.join(DOCS, os.path.basename(path).replace(".json", ".md")), profile(d, os.path.basename(path)))
    write(os.path.join(DOCS, "TRACEABILITY.md"), traceability(occs, proposed))
    adj = json.load(open(os.path.join(DATA, "adjacent-occupations.json"), encoding="utf-8"))
    write(os.path.join(DOCS, "ADJACENT.md"), adjacent(adj))
    print("wrote", len(occs), "profiles, TRACEABILITY.md and ADJACENT.md")


if __name__ == "__main__":
    main()

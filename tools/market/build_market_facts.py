"""Build the market facts ledger from the checked figures.

    python tools/market/build_market_facts.py

Reads docs/product/market-facts.json (figures opened on the O*NET OnLine and BLS pages, with their date) and writes docs/product/MARKET_FACTS.md,
including the totals, computed here so every number in the ledger can be traced. Edit the data, never the generated document.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "docs", "product", "market-facts.json")
OUT = os.path.join(ROOT, "docs", "product", "MARKET_FACTS.md")


def n(x):
    return "n/a" if x is None else f"{x:,}"


def main():
    d = json.load(open(SRC, encoding="utf-8"))
    rows = d["rows"]
    core = [r for r in rows if r["group"] == "core"]
    adj = [r for r in rows if r["group"] != "core"]
    adj_distinct = [r for r in adj if not r.get("duplicateOf") and r["ownEmployment"] is not None]
    no_own = [r for r in adj if r["ownEmployment"] is None]

    core_w = sum(r["ownEmployment"] for r in core)
    adj_w = sum(r["ownEmployment"] for r in adj_distinct)
    core_o = sum(r["openings"] for r in core)
    adj_o = sum(r["openings"] for r in adj_distinct)
    not_electrical = [r for r in adj_distinct if r["soc"] in ("49-9071", "47-2061", "11-9021", "47-1011")]
    ne_w = sum(r["ownEmployment"] for r in not_electrical)
    ne_o = sum(r["openings"] for r in not_electrical)
    bright_yes = [r for r in adj if r["bright"]]
    bright_no = [r for r in adj if not r["bright"]]
    listed_with_children = sum(r["ownEmployment"] for r in adj if r["ownEmployment"] is not None) + 913300 + 510600  # the two child codes carry the parent's figure

    L = []
    L += ["# Market facts ledger", "",
          "> Generated by `tools/market/build_market_facts.py` from `docs/product/market-facts.json`. Do not edit this file; edit the data.", "",
          f"Figures were opened on **{d['retrieved']}** on each occupation's O*NET OnLine page and, where one exists and opened, its BLS Occupational Outlook Handbook (OOH) page. "
          f"Employment is for {d['dataYear']}; projections are for {d['projectionPeriod']}. O*NET data is used under CC BY 4.0 (U.S. Department of Labor, Employment and Training Administration).", "",
          "**Status of every figure here:** read from the live page on the date above, second-hand through a summarising fetch tool. Spot-check any figure before it is quoted. Blank means the page would not open or did not show the figure; nothing is filled from memory.", "",
          "The market sizes, the program and device counts and the prices in the market view are **not in this ledger**: they are the owner's business assumptions and cannot be verified from these pages (see the last section).", "",
          "## 1. The market document's claims against the pages", "",
          "| Claim | Result | Evidence |", "|---|---|---|",
          f"| About 6.7 million workers across 24 occupations | **Not reproducible.** Counting each code once on one basis gives about **{(core_w + adj_w) / 1e6:.1f} million** | Core six {n(core_w)}; adjacent codes with their own figure {n(adj_w)} (section 3) |",
          f"| About 700,000 annual openings | **About {(core_o + adj_o) / 1000:.0f},000**, and {ne_o * 100 // (core_o + adj_o)} percent of those are maintenance workers, laborers, construction managers and supervisors | Core {n(core_o)}; adjacent {n(adj_o)}; the four non-electrical groups {n(ne_o)}. The O*NET openings unit is annual where the OOH confirms it; for some codes it is unconfirmed |",
          f"| All 18 adjacent occupations are Bright Outlook | **False for {len(bright_no)}:** " + ", ".join(f"{r['soc']} {r['title'].split(',')[0]}" for r in bright_no) + f". The other {len(bright_yes)} carry the flag | Read on each O*NET page; reasons are the growth bands the pages show |",
          "| 24 occupations | **23 distinct.** 49-2098 is in the core six and in the adjacent list | Section 2 |",
          "| Codes and titles match O*NET | Mostly. 49-9021 is the HVACR title; 49-2095 is powerhouse and substation repairers, not power-line installers; 47-2152.04, 47-1011.03 and 47-4011.01 are specialties that show their parent's figures; 47-1011 belongs with construction | Section 2 |", "",
          "## 2. Every occupation", "",
          "Own figure means the number is for that code alone; a parent figure means the page repeats a larger group's number. Openings are O*NET's projected openings per year (2025-2035); where the OOH confirms the unit it agrees.", "",
          "| SOC | Occupation (as on the page) | Group | Workers (own) | Scope | Openings | Bright Outlook | BLS OOH | Note |", "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        bls = r["bls"]
        bl = "not opened or none" if not bls else f"{n(bls['employment'])} workers, {bls['change']} growth, median {bls['medianPay']}"
        L.append(f"| {r['soc']} | {r['title']} | {r['group']} | {n(r['ownEmployment'])} | {r['scope']} | {n(r['openings'])} | {'Yes' if r['bright'] else 'No'}: {r['brightWhy']} | {bl} | {r['note']} |")
    L += ["",
          "## 3. How the worker total is built", "",
          "| Step | Workers |", "|---|---|",
          f"| Core six (own figures) | {n(core_w)} |",
          f"| Adjacent codes that have their own figure ({len(adj_distinct)} codes; excludes the duplicate 49-2098 and the {len(no_own)} specialties that only repeat a parent) | {n(adj_w)} |",
          f"| **All distinct occupations, one basis** | **{n(core_w + adj_w)}** |",
          f"| For comparison: adjacent rows as listed, with the parents counted again under their child codes | {n(listed_with_children)} |",
          f"| Of the adjacent total, general maintenance, construction laborers, construction managers and first-line supervisors | {n(ne_w)} ({ne_w * 100 // adj_w} percent) |", "",
          "The four specialties without their own figure are " + ", ".join(r["soc"] for r in no_own) + ". Their workers are inside their parent codes. So the headline says 24 occupations and 6.7 million, but there are 23 distinct occupations, about "
          f"{(core_w + adj_w) / 1e6:.1f} million workers on this basis, and most of the adjacent workers are not electrical workers.", "",
          "## 4. Corrections to our own documents", "",
          "| Where | Was | Is |", "|---|---|---|",
          "| `docs/product/PRD.md` section 4.1, helpers | about 85,000 | 65,000 |",
          "| `docs/product/PRD.md` section 4.1, building inspectors | about 106,000 | 153,900 |",
          "| `docs/product/PRD.md` section 4.1, solar PV installers | about 22,000 | 31,100 |",
          "| `docs/occupations/` profiles | worker, growth and openings figures from an earlier research pass | the figures above, once the profile data is regenerated |", "",
          "## 5. Owner assumptions not checked here", "",
          "| Figure in the market view | Status | How to check |", "|---|---|---|",
          "| Primary education market of $26 million | **Owner's estimate, not verified** | Build it from the counts below |",
          "| Adjacent market of $34.6 million; combined $60.6 million | **Owner's estimate; also rests on the 24-occupation and worker figures, which do not reconcile** | Rebuild after the counts below |",
          "| 6,400 programs | **Not verified** | Count high-school career and technical programs and community college programs for electrician training (U.S. education statistics, program completions by instructional program), and registered electrician apprenticeship programs (U.S. Department of Labor registered apprenticeship data); add inspector continuing-education providers |",
          "| 15 devices per program | **Not verified** | Ask pilot programs and compare with zSpace installed-base data |",
          "| $250 to $375 per device | **Not verified** | Compare with zSpace price lists and quotes from pilot buyers |",
          "| Penetration and revenue | **Not verified** | Set from pilot and sales data, not public figures |",
          "| Licence cost of the installation codes | **Not modelled** (the market view says so) | Needs the owner's licence decisions (`docs/CONTENT_POLICY.md`) |", "",
          "## 6. Still to do", "",
          "- A person spot-checks the figures the deck will quote directly on the live pages (the pages were read through a summarising tool).",
          "- The BLS OEWS national pages and several OOH pages (alarm installers, elevator installers, telecom installers, first-line supervisors) did not open; a person can open them in a browser to fill the blanks.",
          "- Decide the basis once and state it in the deck: O*NET and OOH 2025 employment, each code counted once.",
          "- Build the program, device and price counts from public data and pilot quotes before any dollar figure goes in front of stakeholders."]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L) + "\n")
    print("core", core_w, "adjacent", adj_w, "total", core_w + adj_w, "| openings", core_o + adj_o, "| bright", len(bright_yes), len(bright_no))


if __name__ == "__main__":
    main()
